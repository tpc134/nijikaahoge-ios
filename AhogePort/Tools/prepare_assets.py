"""Structured conversion of the supplied Android data, without changing geometry."""
import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
ALIASES = {'多力多滋': 'bag', '多力多滋2': 'overlay', '涼': 'ryo',
           '喜多': 'kita', '位圖字體': 'font', '牆壁': 'wall',
           **{'粒子' + (str(i) if i != 1 else ''): 'particle' + str(i)
              for i in range(1, 14)}}


def lit(v):
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=True)
    if isinstance(v, bool):
        return 'true' if v else 'false'
    s = format(float(v), '.9g')
    return s + ('f' if '.' in s or 'e' in s else '.0f')


def arr(a):
    return '{' + ','.join(lit(float(x)) for x in a) + '}'


def points(a):
    return '{' + ','.join('Point(' + lit(x) + ',' + lit(y) + ')' for x, y in a) + '}'


def generate(data, atlas):
    out = ['// Generated by Tools/prepare_assets.py. Geometry is unmodified.',
           '#include "AHCore.hpp"', 'namespace ah {', 'Data makeData() {', 'Data d;']
    for name, t in data['types'].items():
        out += ['{ Type t;', 't.name=' + lit(name) + ';', 't.kind=' + lit(t['kind']) + ';']
        if 'image' in t:
            out += ['t.image=' + lit(t['image']) + ';', 't.iw=' + lit(t['w']) + ';t.ih=' + lit(t['h']) + ';']
        for an, a in t.get('anims', {}).items():
            out += ['{ Anim a;', 'a.name=' + lit(an) + ';', 'a.speed=' + lit(a['speed']) + ';']
            for k in ('loop', 'pingPong', 'repeatCount', 'repeatTo'):
                if k in a:
                    out += ['a.' + k + '=' + (str(a[k]) if k.startswith('repeat') else lit(a[k])) + ';']
            for f in a['frames']:
                out += ['{ Frame f;', 'f.file=' + lit(f['file']) + ';']
                out += ['f.' + k + '=' + lit(f.get(k, 1)) + ';' for k in ('w', 'h', 'ox', 'oy', 'dur')]
                poly = f.get('poly', [])
                out += ['f.poly=clean(' + points(list(zip(poly[::2], poly[1::2]))) + ');',
                        'f.triangles=triangulate(f.poly);', 'f.ips=' + points(f.get('ips', [])) + ';',
                        'a.frames.push_back(f); }']
            out += ['t.anims[a.name]=a; }']
        out += ['d.types[t.name]=t; }']
    for e in data['instances']:
        out += ['{ Desc e;']
        for k in ('type', 'anim'):
            if k in e:
                out += ['e.' + k + '=' + lit(e[k]) + ';']
        for k in ('x', 'y', 'w', 'h', 'angle', 'ox', 'oy'):
            out += ['e.' + k + '=' + lit(e.get(k, .5 if k in ('ox', 'oy') else 0)) + ';']
        for k in ('layer', 'z', 'frame'):
            out += ['e.' + k + '=' + str(e.get(k, 0)) + ';']
        out += ['e.visible=' + lit(e.get('visFlag', True)) + ';',
                'e.playing=' + lit(e.get('playing', True)) + ';',
                'e.ivars=' + arr(e.get('ivars', [])) + ';',
                'e.color={{' + ','.join(lit(v) for v in e['color']) + '}};']
        for k in ('physics', 'drag', 'sine'):
            out += ['e.' + k + '=' + arr(e.get('props', {}).get(k, [])) + ';']
        out += ['e.particles=' + arr(e.get('particles', [])) + ';']
        if 'font' in e:
            f = e['font']
            out += ['e.hasFont=true;', 'e.text=' + lit(f[0]) + ';', 'e.charset=' + lit(f[4]) + ';',
                    'e.fontW=' + lit(f[2]) + ';e.fontH=' + lit(f[3]) + ';e.fontSpacing=' + lit(f[7]) + ';',
                    'e.hAlign=' + str(f[9]) + ';e.vAlign=' + str(f[10]) + ';']
        out += ['d.instances.push_back(e); }']
    for name, rect in atlas['regions'].items():
        x, y, w, h = rect
        s = atlas['size']
        out += ['{ Region r; r.file="atlas.png";',
                'r.u0=' + lit(x/s) + ';r.v0=' + lit(y/s) + ';r.u1=' + lit((x+w)/s) + ';r.v1=' + lit((y+h)/s) + ';',
                'd.regions[' + lit(name) + ']=r; }']
    out += ['return d;', '}', '}']
    (ROOT/'Sources/AHData.generated.cpp').write_text('\n'.join(out) + '\n', encoding='ascii')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--android-assets', type=pathlib.Path)
    ap.add_argument('--ffmpeg', type=pathlib.Path)
    ap.add_argument('--regenerate-only', action='store_true')
    args = ap.parse_args()
    if args.regenerate_only:
        generate(json.loads((ROOT/'Tools/data.normalized.json').read_text(encoding='utf-8')),
                 json.loads((ROOT/'Tools/atlas.normalized.json').read_text(encoding='utf-8')))
        print('Regenerated AHData.generated.cpp from bundled structured data.')
        return
    if not args.android_assets or not args.ffmpeg:
        ap.error('Full conversion requires --android-assets and --ffmpeg; otherwise use --regenerate-only.')
    src = args.android_assets
    dest = ROOT/'Resources/AhogeAssets'
    (dest/'frames').mkdir(parents=True, exist_ok=True)
    (dest/'media').mkdir(exist_ok=True)
    data = json.loads((src/'game_data.json').read_text(encoding='utf-8'))
    atlas = json.loads((src/'render_atlas.json').read_text(encoding='utf-8'))
    names = sorted(p.relative_to(src).as_posix() for p in (src/'frames').glob('*.png'))
    remap = {name: 'frames/frame%03d.png' % i for i, name in enumerate(names)}
    for name, renamed in remap.items():
        shutil.copyfile(src/name, dest/renamed)
    for t in data['types'].values():
        if 'image' in t:
            t['image'] = remap[t['image']]
        for a in t.get('anims', {}).values():
            for f in a['frames']:
                f['file'] = remap[f['file']]
    data['types'] = {ALIASES.get(k, k): v for k, v in data['types'].items()}
    for e in data['instances']:
        e['type'] = ALIASES.get(e['type'], e['type'])
    atlas['regions'] = {remap[k]: v for k, v in atlas['regions'].items()}
    atlas['file'] = 'atlas.png'
    shutil.copyfile(src/'small_objects_atlas.png', dest/'atlas.png')
    for i in range(12):
        subprocess.run([str(args.ffmpeg), '-nostdin', '-v', 'error', '-y', '-i',
                        str(src/'media'/('%d.m4a' % i)), '-c:a', 'pcm_s16le',
                        '-ar', '48000', str(dest/'media'/('%d.wav' % i))], check=True)
    data['media'] = ['%d.wav' % i for i in range(12)]
    (ROOT/'Tools/data.normalized.json').write_text(json.dumps(data, ensure_ascii=True, indent=2), encoding='ascii')
    (ROOT/'Tools/atlas.normalized.json').write_text(json.dumps(atlas, indent=2), encoding='ascii')
    (ROOT/'Tools/asset_name_map.json').write_text(json.dumps(remap, ensure_ascii=True, indent=2), encoding='ascii')
    generate(data, atlas)
    print('Converted %d original images, 12 PCM clips, %d instances.' % (len(remap), len(data['instances'])))


if __name__ == '__main__':
    main()
